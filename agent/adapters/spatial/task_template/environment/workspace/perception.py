# WHY THIS EXISTS. The CLI makes the agent hand-carry strings between calls,
# and the strings have invisible compatibility rules. Measured over v8+v9
# (200 episodes, counted structurally -- see docs/superpowers/specs/
# 2026-08-21-perception-interface-design.md for the counting method, which is
# easy to get wrong):
#
#   * 45 rejected calls, NOT ONE of them a missing capability. 29 were
#     "mask resolution does not match the point map" -- the crop_box rule that
#     perception-3d/SKILL.md spends a third of its length explaining. Writing
#     it down helped (call success 84% -> 96% in v5) but never zeroed it:
#     knowledge can be forgotten, a type cannot.
#   * detect -> measure took a median of 4 conversation turns, because the
#     agent must run detect, read a path out of the JSON, run reconstruct,
#     read another path, then finally measure.
#   * 324 array-producing calls yielded only 46 renders -- while 96% of the
#     renders that DID happen were then looked at. The appetite is there; the
#     cost of a separate render call + remembering its path is what is not.
#
# So the fix is not more documentation. `scene.find("stove").where()` cannot
# express the grid mismatch: alignment is this module's private business.
#
# WHAT THIS IS NOT. `show()` still returns a path the agent has to `view`.
# SpatialClaw injects the image into the next message; we cannot do that from
# inside a task container, and pretending otherwise in the docs would just
# move the gap somewhere harder to see.


class PerceptionError(RuntimeError):
    """A gateway call failed.

    Carries the gateway's own message rather than a summary. The whole point
    of the object layer is to remove rejections, but the ones that remain must
    stay as actionable as the CLI's were -- swallowing a specific complaint
    into "perception failed" would convert problem 2 from "rejected" into
    "silently wrong", which is worse.
    """


def _checked(reply: dict, what: str) -> dict:
    if isinstance(reply, dict) and "error" in reply:
        err = reply["error"]
        msg = err.get("message", err) if isinstance(err, dict) else err
        raise PerceptionError(f"{what}: {msg}")
    return reply


#: Distinguishes "not computed yet" from "computed and found nothing". A plain
#: None cache would re-run the RANSAC fit on every call for scenes with no
#: visible floor -- the case where it is least likely to succeed.
_UNSET = object()


class Camera:
    """One frame's viewpoint. Obtained from `Scene.camera(i)`, never built."""

    def __init__(self, scene: Scene, frame: int, pose) -> None:
        self._scene = scene
        self.frame = frame
        self._pose = pose

    def position(self) -> tuple:
        """Camera centre in world metres (the c2w matrix's translation)."""
        return tuple(float(self._pose[i][3]) for i in range(3))

    # -- axes ----------------------------------------------------------------
    #
    # WHY THESE EXIST. Measured over 844 episodes, the agent asked for camera
    # orientation 324 times and got `AttributeError` every time: `forward` 208,
    # `direction` 59, `orientation` 28, `facing` 12, `view_direction` 6, `dir` 6,
    # `rotation` 5. The information was always there -- the c2w matrix's columns
    # ARE right/up/forward (see `_bearing`) -- we just never exposed it, so every
    # question about where a camera points had to go through `direction_from`
    # on some object or be eyeballed.
    #
    # `where()` is the same story as a NAMING asymmetry rather than a missing
    # quantity: `Thing.where()` exists, so `Camera.where()` was tried 125 times
    # across 98 episodes. Aliasing it costs nothing and removes a whole class of
    # dead turn. Same for `direction_from`/`direction_to`, which `Thing` has and
    # `Camera` did not.
    #
    # Read straight off the pose rather than cached: the pose is fixed at
    # construction, so there is nothing to invalidate.

    def forward(self) -> tuple:
        """Unit vector the camera looks along, in world coordinates."""
        return self._axis(2)

    def right(self) -> tuple:
        """Unit vector to the camera's right, in world coordinates."""
        return self._axis(0)

    def up(self) -> tuple:
        """Unit vector to the camera's up, in world coordinates.

        ⚠️ This is the camera's own up, NOT the real vertical. On a tilted
        photo they differ -- use `Scene.up_vector()` for gravity.
        """
        return self._axis(1)

    def _axis(self, col: int) -> tuple:
        v = [float(self._pose[i][col]) for i in range(3)]
        norm = sum(c * c for c in v) ** 0.5
        return tuple(v) if norm < 1e-9 else tuple(c / norm for c in v)

    def where(self) -> tuple:
        """Alias of `position()`, because `Thing.where()` is spelled that way."""
        return self.position()

    def distance_to(self, other) -> float:
        """Straight-line distance to a Thing or another Camera, in metres.

        WHY THIS EXISTS. `perception-3d` documents `cam_a.distance_to(cam_b)`
        with a worked value, and Camera had no such method: measured 11
        `'Camera' object has no attribute 'distance_to'` in the first 53 trials
        of the run that added that example, against 0 in the two runs before it.
        The card promised it, so the card was creating the error -- the same
        shape as `.forward` (65 occurrences from prose that named an axis with no
        accessor) and `.where` (116 when the only example was deleted).

        Accepts a Camera as well as a Thing because "how far did the camera
        move" is the question this is for. `Thing.distance_to` rejects a Camera,
        which is why the agent could not get here by any other spelling.
        """
        if isinstance(other, Things):
            other = other._first()
        if isinstance(other, Camera):
            b = other.position()
        elif isinstance(other, Thing):
            b = other.where()
        else:
            raise TypeError(
                "distance_to takes a Camera or an object from find(), "
                f"not {type(other).__name__}"
            )
        a = self.position()
        return math.sqrt(sum((a[i] - b[i]) ** 2 for i in range(3)))

    def direction_from(self, other) -> str:
        """Where this camera lies as seen FROM `other` (a Thing or Camera)."""
        origin = other.position() if isinstance(other, Camera) else other.where()
        return self._scene._bearing(origin, self.position(), self._pose)

    def direction_to(self, other) -> str:
        """Where `other` lies as seen from this camera -- the usual direction."""
        target = other.position() if isinstance(other, Camera) else other.where()
        return self._scene._bearing(self.position(), target, self._pose)

    def __repr__(self) -> str:
        x, y, z = self.position()
        fx, fy, fz = self.forward()
        return (
            f"<Camera frame={self.frame} at ({x:.2f}, {y:.2f}, {z:.2f})m "
            f"looking along ({fx:.2f}, {fy:.2f}, {fz:.2f})>"
        )


class Thing:
    """One detected object, tied to the Scene that found it.

    Holds the mask array path and the frame it was found in, so the
    measurement methods can assemble a correct `measure` call without the
    caller ever naming an artifact.
    """

    def __init__(
        self, scene: Scene, label: str, frame: int, detection: dict, instance: int
    ) -> None:
        self._scene = scene
        self.label = label
        self.frame = frame
        self._detection = detection
        self._instance = instance

    @property
    def score(self):
        scores = self._detection.get("scores") or []
        try:
            return float(scores[self._instance])
        except (IndexError, TypeError, ValueError):
            return None

    @property
    def box(self):
        """Pixel box (x1, y1, x2, y2) on the ORIGINAL image grid, or None."""
        boxes = self._detection.get("box_xyxy") or self._detection.get("boxes")
        try:
            return tuple(float(v) for v in boxes[self._instance])
        except (IndexError, TypeError, ValueError):
            return None

    def _masks_path(self):
        return (self._detection.get("arrays") or {}).get("masks")

    def where(self) -> tuple:
        """3D position in world metres: (x, y, z).

        This is the method the whole layer exists for. It runs whatever is
        needed -- reconstructing the scene if that has not happened yet, and
        routing around the crop_box grid mismatch when the depth model
        center-cropped -- without the caller knowing either happened.
        """
        return self._scene._locate(self)

    def distance_to(self, other) -> float:
        """Straight-line distance to another object, in metres.

        Accepts either a Thing or the Things list that `find()` returns,
        because `a.distance_to(scene.find("sink"))` is the spelling that comes
        naturally and rejecting it would recreate exactly the bookkeeping this
        layer exists to remove. A string is still refused -- that is the CLI
        habit of passing an artifact path, and quietly accepting it would turn
        a clear error into a wrong number.
        """
        if isinstance(other, Things):
            other = other._first()
        if not isinstance(other, Thing):
            raise TypeError(
                "distance_to takes another object from find(), "
                f"not {type(other).__name__}"
            )
        a, b = self.where(), other.where()
        return math.sqrt(sum((a[i] - b[i]) ** 2 for i in range(3)))

    def direction_from(self, other) -> str:
        """Where this object lies as seen FROM `other`.

        `other` may be a Camera (answered in that camera's own axes) or another
        Thing (answered in the viewing camera's axes, with the other object as
        the origin).

        Returns front/behind crossed with left/right (e.g. "front-right"), or
        "above"/"below" when the vertical offset dominates.

        WHY THING IS ACCEPTED. It used to take a Camera only, and that was the
        single largest capability gap in the object layer: 205 attempted
        `Thing.direction_from(Thing)` calls across the v23 and v24 runs, every
        one dying on `AttributeError: 'Thing' object has no attribute '_pose'`.
        Camera-anchored questions score 64.2% against 36.8% for questions
        relating two non-camera things (Fisher p=0.00030), and a review found
        the cause is not a coordinate-frame error but exactly this: camera
        questions are one call in the right frame, object-to-object questions
        had no primitive at all.

        ⚠️ WHAT FRAME THIS IS, precisely. A Thing has no orientation, so
        "to the left of the chair" is genuinely ambiguous. This answers the
        reading that is well defined: the offset from `other` to `self`,
        expressed in the VIEWING CAMERA's left/right/front axes. It is
        therefore "from where the chair is, the lamp is to the front-right
        *as the photographer sees it*" -- not "to the chair's own left", which
        would need the chair's heading. For that reading, work out which way
        the object faces and mirror accordingly; see the object-relations and
        spatial-frames skills.
        """
        if isinstance(other, Camera):
            return self._scene._direction(self, other)
        # Reference frame: the camera whose frame this object was detected in,
        # so a two-object question stays in the viewpoint the question is asked
        # from rather than silently adopting frame 0.
        # WHICH CAMERA'S AXES. Taking it from `other` was a bug: the reference
        # frame is a property of the COMPARISON, not of whichever object
        # happens to be the argument, so `a.direction_from(b)` and
        # `b.direction_from(a)` projected in two different cameras and stopped
        # being opposites. Caught in the wild (MMSI_806__tYpC8Ct printed
        # "chair to bed: behind-right" and "bed to chair: behind-left" in one
        # script -- both "behind" is impossible in a single frame).
        #
        # Fixed by using the LOWEST frame index the two objects were detected
        # in, so the pair maps to one camera regardless of call order. Lowest
        # rather than either operand's because it is symmetric and because
        # earlier frames are the ones the question tends to be phrased from.
        #
        # A missing/None frame falls back to the other object's, then to 0 --
        # spelled out rather than `or 0`, which would collapse a legitimate
        # frame 0 with a missing attribute and answer in the wrong axes with no
        # trace.
        frames = [
            f
            for f in (getattr(other, "frame", None), getattr(self, "frame", None))
            if f is not None
        ]
        camera = self._scene.camera(int(min(frames)) if frames else 0)
        return self._scene._direction_between(self, other, camera)

    def direction_to(self, other) -> str:
        """Where `other` lies as seen from THIS object, in the camera's frame.

        The inverse of direction_from, and the thing the agent kept reaching
        for: 10 attempted `.direction_to` accesses across the v23/v24 runs.
        """
        return other.direction_from(self)

    #: Aliases for names the agent actually typed. Measured across v23+v24:
    #: 21 attempts at `.box_xyxy` (the CLI's name for the same field), 18 at
    #: `.centroid_px`, 8 at `.centroid`, 4 at `.bbox_px`, 34 at `._score`.
    #: Every one of those was an AttributeError -- the agent knew what it
    #: wanted and guessed a plausible name. Accepting its vocabulary is
    #: cheaper than teaching ours, and it removes a class of dead turn that no
    #: amount of skill-card wording would have prevented.
    @property
    def box_xyxy(self) -> tuple:
        """Pixel corners, same as `.box` (the CLI spells it this way)."""
        return self.box

    @property
    def bbox_px(self) -> tuple:
        """Pixel corners, same as `.box`."""
        return self.box

    def show(self) -> str:
        """Render this object's mask over its frame; returns the image path.

        Follow with `view <path>` to actually look at it. That second step is
        the one thing this layer cannot remove from inside a container.
        """
        return self._scene._show_mask(self)

    def __repr__(self) -> str:
        score = self.score
        tail = f" score={score:.2f}" if isinstance(score, float) else ""
        return f"<Thing {self.label!r} frame={self.frame}{tail}>"


class Scene:
    """The frames of one question, and everything derived from them.

    Built by `look()`. Reconstruction is lazy: `find()` alone never pays for
    3D, because plenty of questions are answered by detection or by eye. The
    first call that genuinely needs metric structure triggers it once, and the
    result is cached for the rest of the scene's life.
    """

    def __init__(self, frames: list) -> None:
        if not frames:
            raise ValueError(
                "look() needs at least one frame, e.g. look('frame_0.png')"
            )
        self.frames = list(frames)
        self._recon = None
        self._detections: dict = {}
        self._up = _UNSET

    # -- lazily-built 3D -----------------------------------------------------

    def _reconstruction(self) -> dict:
        if self._recon is None:
            body = {
                "images": [gateway_image_path(f) for f in self.frames],
                "frame_indices": list(range(len(self.frames))),
            }
            body.update(request_kwargs())
            self._recon = _checked(call("/reconstruct", body), "reconstruct")
        return self._recon

    def camera(self, frame: int = 0) -> Camera:
        """The viewpoint of one frame (default: the first)."""
        recon = self._reconstruction()
        # /reconstruct returns camera_poses as a DICT keyed by the absolute
        # frame index as a STRING (perception_gateway.py:1343-1347), not a list.
        # Indexing it with an int raised KeyError; caught by a live call, not by
        # the unit tests, whose fixture used a list. Accept both so a fixture or
        # a future gateway change cannot silently break this.
        poses = recon.get("camera_poses") or {}
        pose = None
        if isinstance(poses, dict):
            pose = poses.get(str(frame), poses.get(frame))
        elif frame < len(poses):
            pose = poses[frame]
        if pose is None:
            have = (
                sorted(poses.keys()) if isinstance(poses, dict) else range(len(poses))
            )
            raise PerceptionError(
                f"no camera pose for frame {frame}; this scene has poses for "
                f"{list(have)} (it was built from {len(self.frames)} frame(s))"
            )
        return Camera(self, frame, pose)

    # -- detection -----------------------------------------------------------

    def up_vector(self) -> tuple:
        """Real vertical, recovered by fitting the ground plane.

        WHY THIS EXISTS. The world frame is the FIRST CAMERA's frame, not a
        gravity-aligned one -- the gateway calls the raw reconstruct and skips
        upstream's alignment layer, so the first camera's c2w is the identity
        and `+Y` means "up in the first photo". Measured on a real frame pair,
        the fitted ground normal sits 35.8 degrees off +Y, and one object's
        height reads 0.084 m from raw Y against 0.330 m along true up -- a 4x
        error. Questions anchored on the camera are unaffected (they use the
        camera's own axes); questions relating two objects are not, and score
        34.0% against 70.2% for camera-anchored ones (Fisher p=0.000225).

        WHY IT IS A METHOD AND NOT A DOCUMENTED RECIPE. The first version of
        this was exactly that -- a skill card telling the agent to run
        `geom.py fit-ground-plane --points <path> --confidence <path>`. It was
        opened 9 times and executed ZERO times, because this layer deliberately
        does not expose array paths. The card taught a route the API does not
        have. Measured, not assumed: the fix for "the agent won't do the extra
        step" is to remove the step, not to word the instruction better.

        Returns a unit vector, or None when no usable ground was found (few
        inliers, or the scene has no visible floor) -- None is a real answer
        meaning "do not trust height from this reconstruction", not an error.
        """
        if self._up is not _UNSET:
            return self._up
        self._up = None
        recon = self._reconstruction()
        arrays = recon.get("arrays") or {}
        points, conf = arrays.get("points"), arrays.get("confidence")
        if not (points and conf):
            return self._up
        try:
            import subprocess

            out = subprocess.run(
                [
                    sys.executable,
                    os.path.join(os.path.dirname(os.path.abspath(__file__)), "geom.py"),
                    "fit-ground-plane",
                    "--points",
                    to_container_path(points),
                    "--confidence",
                    to_container_path(conf),
                ],
                capture_output=True,
                text=True,
                timeout=300,
                # check=False on purpose: a failed fit must return None so the
                # caller can say "height is not measurable here", not raise.
                check=False,
            )
            fit = json.loads(out.stdout or "{}")
        except subprocess.TimeoutExpired as exc:
            # A timeout is NOT "no ground here". Conflating them would report a
            # slow scene as groundless, and `None` is what callers read as
            # "height is not measurable" -- so a slow fit would silently become
            # a wrong claim about the scene. Raise instead: the caller can
            # retry or fall back explicitly.
            #
            # The fit itself was O(points * iterations) until geom.py started
            # subsampling; on a real 115 MB / 47M-point reconstruction it took
            # longer than the agent's 120 s tool timeout, and now takes 11 s.
            # This branch should therefore be unreachable in practice; it exists
            # so that if it ever fires again the failure is loud.
            raise PerceptionError(
                "ground-plane fitting timed out, so real vertical is unknown "
                "for this scene. This is a tool failure, not a finding: do not "
                "treat it as 'no ground'."
            ) from exc
        except (OSError, ValueError, subprocess.SubprocessError):
            return self._up
        # A weak fit is worse than no fit: it would silently rotate every
        # height comparison by whatever the noise happened to be.
        if not fit.get("success") or (fit.get("n_inliers") or 0) < 1000:
            return self._up
        n = fit.get("normal") or []
        if len(n) != 3:
            return self._up
        mag = math.sqrt(sum(float(v) ** 2 for v in n))
        if mag < 1e-9:
            return self._up
        self._up = tuple(float(v) / mag for v in n)
        return self._up

    def height_of(self, thing) -> float:
        """How high an object sits, along REAL vertical rather than +Y.

        This is the projection the skill card used to ask the agent to write by
        hand. Use it for anything meaning above/below, taller, resting on,
        stacked, or same height -- reading `where()[1]` for those is reading a
        frame that may be tilted by tens of degrees.

        Raises when no ground could be fitted, rather than silently falling
        back to +Y: a wrong height that looks right is the failure this whole
        method exists to prevent.
        """
        up = self.up_vector()
        if up is None:
            raise PerceptionError(
                "no ground plane could be fitted for this scene, so there is no "
                "reliable vertical -- height cannot be measured. Compare what "
                "the frames show instead, and say the claim rests on the image."
            )
        pos = thing.where() if hasattr(thing, "where") else tuple(thing)
        return sum(p * u for p, u in zip(pos, up))

    def find(self, prompt: str, frame: int = 0) -> Things:
        """Find objects matching a text prompt. Returns a Things list.

        A Things list forwards attribute access to its first element, so the
        common single-object case reads as `scene.find("stove").where()` while
        a genuinely plural result can still be indexed or iterated.
        """
        key = (prompt, frame)
        if key not in self._detections:
            body = {
                "image": gateway_image_path(self.frames[frame]),
                "frame_index": frame,
                "prompt": prompt,
            }
            body.update(request_kwargs())
            self._detections[key] = _checked(call("/detect", body), f"find({prompt!r})")
        detection = self._detections[key]
        count = len(detection.get("scores") or []) or (
            1 if detection.get("found") else 0
        )
        return Things(
            [Thing(self, prompt, frame, detection, i) for i in range(count)],
            prompt,
        )

    # -- measurement ---------------------------------------------------------

    def _locate(self, thing: Thing) -> tuple:
        """3D centroid of a Thing, routing around the crop_box grid mismatch.

        The direct path is `measure --op centroid`, which needs the mask and
        the point map to share a pixel grid. When DA3 center-cropped (a
        non-null crop_box, 36% of frames in this task set) they do not, and
        that single condition produced 29 of the 45 rejections in v8+v9.
        Rather than teach the workaround, do it: take the mask's 2D centroid
        on the original grid, shift it by the crop offset, and ask for the 3D
        position of that one pixel. Same answer, no grid to match.
        """
        recon = self._reconstruction()
        points = (recon.get("arrays") or {}).get("points")
        masks = thing._masks_path()
        if not points:
            raise PerceptionError("reconstruct returned no point map")
        if not masks:
            raise PerceptionError(
                f"{thing.label!r} was not found in frame {thing.frame}, so it has "
                "no mask to measure"
            )

        crop = recon.get("crop_box")
        if not crop:
            body = {
                "op": "centroid",
                "points": from_container_path(points),
                "masks": from_container_path(masks),
                "frame_index": thing.frame,
                "instance": thing._instance,
            }
            body.update(request_kwargs())
            reply = _checked(call("/measure", body), f"locate({thing.label!r})")
            # The key is `centroid_xyz_m`, not `centroid`
            # (perception_gateway.py:1926-1932). Guessing it cost a KeyError
            # that no unit test caught, because the fixture used the invented
            # name and this branch only runs when crop_box is null -- the live
            # tests had all gone down the cropped path. Third time a guessed
            # response key has broken this file; read the gateway, do not guess.
            xyz = reply.get("centroid_xyz_m") or reply.get("centroid")
            if not xyz:
                raise PerceptionError(
                    f"/measure op=centroid returned no centroid for "
                    f"{thing.label!r}; reply keys were {sorted(reply)}"
                )
            return tuple(float(v) for v in xyz)

        cx, cy = self._mask_centroid_px(masks, thing._instance)
        px = round(cx) - int(crop["left"])
        py = round(cy) - int(crop["top"])
        px = max(0, min(px, int(crop["width"]) - 1))
        py = max(0, min(py, int(crop["height"]) - 1))
        body = {
            "op": "depth_at",
            "points": from_container_path(points),
            "pixels": [[px, py]],
            "frame_index": thing.frame,
        }
        body.update(request_kwargs())
        reply = _checked(call("/measure", body), f"locate({thing.label!r})")
        # /measure op=depth_at returns points: [{"pixel", "xyz_m", "depth_m",
        # "valid"}] -- see perception_gateway.py:1744-1758. An earlier version
        # of this line guessed a flat `positions: [[x,y,z]]` and indexed
        # `pos[0][:3]`, which raised KeyError against the real dict. It passed
        # the unit tests because the fake reply in the fixture had the invented
        # shape; only a live call caught it. Read the gateway, do not guess.
        pts = reply.get("points") or []
        xyz = pts[0].get("xyz_m") if pts and isinstance(pts[0], dict) else None
        if not xyz:
            # valid=false is normal on sky, glass and thin edges rather than an
            # error, so say what to do about it instead of just failing.
            raise PerceptionError(
                f"the depth model has no finite estimate at the centre of "
                f"{thing.label!r} (common on sky, glass and thin edges). Try "
                f"{thing.label!r}.show() to see what was selected, or measure a "
                f"different object."
            )
        return tuple(float(v) for v in xyz[:3])

    @staticmethod
    def _mask_centroid_px(masks_path: str, instance: int) -> tuple:
        """2D centroid of a mask, on the mask's own (original) grid.

        Reads the array locally. The gateway writes artifacts into the shared
        work dir, which this container has mounted, so no round trip is
        needed -- and `maskutil.py centroid` already does exactly this.
        """
        try:
            import numpy as _np
        except ImportError as exc:
            # This is the crop_box detour -- the code path that exists to stop
            # the 29 grid-mismatch rejections. If it dies on a bare
            # ModuleNotFoundError the caller sees an import error where they
            # asked for a coordinate, and the obvious guess is that the tool is
            # broken rather than that the interpreter is wrong.
            #
            # The task image has numpy 2.2.6, but `python3` on PATH inside the
            # agent's container resolves to the openhands runtime's own 3.12,
            # which does NOT (that mismatch already cost 17 failed calls in the
            # m0a run, which is why perception.py's shebang pins
            # /usr/local/bin/python3).
            raise PerceptionError(
                "numpy is required to locate an object in a cropped scene, and "
                "it is missing from this interpreter. Run this with "
                "/usr/local/bin/python3 (the task image's own python), not the "
                f"one on PATH -- sys.executable is {sys.executable}"
            ) from exc

        arr = _np.load(to_container_path(masks_path))
        if arr.ndim == 3:
            arr = arr[instance]
        ys, xs = _np.nonzero(arr)
        if len(xs) == 0:
            raise PerceptionError("mask is empty, nothing to locate")
        return float(xs.mean()), float(ys.mean())

    def _direction_between(self, thing, other, camera: Camera) -> str:
        """Bearing of `thing` from `other`, in `camera`'s axes.

        Same projection as _direction, but the origin is another object's
        position instead of the camera's. Factored so the two share the
        axis-extraction and the naming thresholds -- if they drifted apart,
        "left" would mean different things depending on which overload was
        called, which is worse than not having the overload.
        """
        return self._bearing(other.where(), thing.where(), camera._pose)

    def _direction(self, thing: Thing, camera: Camera) -> str:
        """Bearing of a Thing in a camera's own frame.

        The c2w matrix's columns are the camera's right/up/forward axes in
        world space, so projecting the object offset onto them gives the
        answer in the frame the question actually means.
        """
        return self._bearing(camera.position(), thing.where(), camera._pose)

    def _bearing(self, origin, target, pose) -> str:
        """Name the direction from `origin` to `target` in `pose`'s axes.

        Shared by _direction (origin = a camera) and _direction_between
        (origin = another object) so the two cannot drift: if the naming
        thresholds differed between overloads, "left" would mean different
        things depending on which one was called, which is worse than not
        offering the overload at all.
        """
        offset = [target[i] - origin[i] for i in range(3)]
        right = [float(pose[i][0]) for i in range(3)]
        up = [float(pose[i][1]) for i in range(3)]
        fwd = [float(pose[i][2]) for i in range(3)]

        def dot(a, b):
            return sum(a[i] * b[i] for i in range(3))

        r, u, f = dot(offset, right), dot(offset, up), dot(offset, fwd)
        if abs(u) > abs(r) and abs(u) > abs(f):
            return "above" if u > 0 else "below"
        # A near-zero depth component means the two are at the same distance
        # along the viewing axis, so NEITHER "front" nor "behind" is true --
        # report the side alone. Without this, `f == 0` fell through to
        # "behind", and two objects side by side at equal depth both came back
        # "behind" each other, which cannot be true in one frame. The guard is
        # relative to the lateral offset, not an absolute distance, so it scales
        # with the scene instead of hard-coding a metre threshold.
        if abs(f) < 0.18 * max(abs(r), 1e-9):
            return "right" if r > 0 else "left"
        depth = "front" if f > 0 else "behind"
        # Only a genuinely small lateral offset reads as straight ahead.
        # 0.18 is tan(10 degrees), i.e. a 20-degree cone around the axis.
        # This was 0.36 (a 40-degree cone) and a test caught it: an object at
        # (1, 0, 3) -- which any person would call "ahead and to the right" --
        # came back as plain "front". The failure mode matters more on one
        # side than the other: MMSI options are mostly left/right/front
        # distinctions, so collapsing a real side into "front" loses the
        # answer, while calling a near-axis object "front-right" is merely
        # over-specific.
        if abs(f) > 1e-6 and abs(r / f) < 0.18:
            return depth
        side = "right" if r > 0 else "left"
        return f"{depth}-{side}"

    # -- looking -------------------------------------------------------------

    def _show_mask(self, thing: Thing) -> str:
        masks = thing._masks_path()
        if not masks:
            raise PerceptionError(f"{thing.label!r} has no mask to show")
        body = {
            "kind": "overlay",
            "array": from_container_path(masks),
            "image": gateway_image_path(self.frames[thing.frame]),
            "frame_index": thing.frame,
            "instance": thing._instance,
        }
        body.update(request_kwargs())
        reply = _checked(call("/render", body), f"show({thing.label!r})")
        return reply.get("path", "")

    def show(self, frame: int = 0) -> str:
        """Path of one frame, for symmetry with Thing.show()."""
        return self.frames[frame]

    def __repr__(self) -> str:
        state = "3D ready" if self._recon is not None else "3D not built yet"
        return f"<Scene {len(self.frames)} frame(s), {state}>"


class Things(list):
    """The result of `find()`: a list that also acts like its first element.

    `find()` is genuinely plural -- "how many chairs" needs every hit -- but
    the overwhelmingly common case is one object, and forcing `[0]` onto every
    call is exactly the kind of bookkeeping this layer removes. So
    `scene.find("stove").where()` works, and `len(scene.find("chair"))` still
    answers the counting question.
    """

    def __init__(self, items, prompt: str) -> None:
        super().__init__(items)
        self._prompt = prompt

    def _first(self) -> Thing:
        if not self:
            raise PerceptionError(
                f"{self._prompt!r} was not found in this frame. Try a different "
                "wording, or look at the frame to check it is there at all."
            )
        return self[0]

    def __getattr__(self, name: str):
        # Only reached for attributes list does not define, so list's own API
        # (append, index, ...) is never shadowed.
        return getattr(self._first(), name)

    def __repr__(self) -> str:
        if not self:
            return f"<no {self._prompt!r} found>"
        if len(self) == 1:
            return repr(self[0])
        return f"<{len(self)}x {self._prompt!r}: {list.__repr__(self)}>"


def look(*frames: str) -> Scene:
    """Start here. Give it the frames of the question, get a Scene back.

        scene = look("frame_0.png", "frame_1.png")
        stove = scene.find("stove")
        stove.where()                          # (x, y, z) in metres
        stove.distance_to(scene.find("sink"))  # metres
        stove.direction_from(scene.camera(0))  # "front-right"
        stove.show()                           # overlay path, then `view` it

    Pass every frame the question involves in ONE call: frames reconstructed
    together share a coordinate frame, which is what makes multi-view and
    camera-motion questions answerable. Separate calls cannot be compared.
    """
    if len(frames) == 1 and isinstance(frames[0], (list, tuple)):
        frames = tuple(frames[0])
    return Scene(list(frames))


